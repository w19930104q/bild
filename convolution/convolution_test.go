func benchConvolve(b *testing.B, w, h int, k *Kernel) {
	img := image.NewRGBA(image.Rect(0, 0, w, h))
	b.ResetTimer()
	for n := 0; n < b.N; n++ {
		benchResult = Convolve(img, k, &Options{Wrap: false})
	}
}
